"""Opt-in PostgreSQL test: temporary shadow tables, no production data writes."""
from contextlib import contextmanager
import os
from unittest.mock import patch

import pytest
from sqlalchemy import text
from sqlalchemy.orm import Session

from app.db import _get_engine
from app.evidence.extractor import _fact_batch_transaction, save_fact_with_evidence, save_claim, merge_fact_evidence
from app.models import Fact
from app.models.material import Claim, Evidence


@pytest.mark.skipif(os.getenv("RUN_POSTGRES_TESTS") != "1", reason="requires PostgreSQL")
def test_batch_commit_and_failure_rollback_use_one_transaction():
    with _get_engine().connect() as connection:
        transaction = connection.begin()
        try:
            for name in ("facts", "evidence", "claims"):
                connection.execute(text(f'CREATE TEMP TABLE "{name}" (LIKE public."{name}" INCLUDING DEFAULTS) ON COMMIT DROP'))
                connection.execute(text(f'ALTER TABLE pg_temp."{name}" ALTER COLUMN id DROP DEFAULT'))
                connection.execute(text(f'ALTER TABLE pg_temp."{name}" ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY'))
            # Accept both a migrated and a not-yet-migrated host for this isolated test.
            connection.execute(text("ALTER TABLE pg_temp.evidence ADD COLUMN IF NOT EXISTS visibility_json TEXT NOT NULL DEFAULT '{}'"))
            session = Session(bind=connection, join_transaction_mode="create_savepoint")
            @contextmanager
            def scope():
                try:
                    yield session
                    session.commit()
                except Exception:
                    session.rollback()
                    raise
            def persist(content):
                fact = Fact(content)
                identifier = save_fact_with_evidence(fact, [Evidence(None, 1, 7, "source", "quote")], "isolated")
                save_claim(Claim(1, content, unit_id=7, quote="quote", fact_id=identifier), "promoted", task_id="isolated")
                return identifier
            with patch("app.evidence.extractor.session_scope", scope):
                with _fact_batch_transaction([{"content": "committed"}], "isolated"):
                    identifier = persist("committed")
                    merge_fact_evidence(identifier, [Evidence(None, 1, 7, "source", "quote")], "isolated", "later")
                    save_claim(Claim(1, "paraphrase", unit_id=7, quote="quote", fact_id=identifier,
                                     assertion_mode="prospective", semantic_profile={"facets": [{"axis": "state", "label": "plan"}]}),
                               "promoted", task_id="isolated")
                    assert session.execute(text("SELECT count(*) FROM pg_temp.facts WHERE content='committed'")).scalar() == 1
                    assert session.execute(text("SELECT count(*) FROM pg_temp.claims WHERE fact_id=:id"), {"id": identifier}).scalar() == 2
                    assert session.execute(text("SELECT assertion_mode FROM pg_temp.facts WHERE id=:id"), {"id": identifier}).scalar() == "unknown"
                with pytest.raises(RuntimeError):
                    with _fact_batch_transaction([{"content": "rolled_back"}], "isolated"):
                        persist("rolled_back")
                        raise RuntimeError("injected failure")
                assert connection.execute(text("SELECT count(*) FROM pg_temp.facts WHERE content='committed'")).scalar() == 1
                for name in ("facts", "claims"):
                    assert connection.execute(text(f"SELECT count(*) FROM pg_temp.{name} WHERE content='rolled_back'")).scalar() == 0
                assert connection.execute(text("SELECT count(*) FROM pg_temp.evidence")).scalar() == 1
            session.close()
        finally:
            transaction.rollback()
